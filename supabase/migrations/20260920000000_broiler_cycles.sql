-- ============================================================
-- Broiler live cycle
--
-- Each livestock_flocks row is one BATCH (cycle) in a coop. A coop is
-- reused by starting a new batch with the same coop_name; closed batches
-- stay as history.
--
-- New on livestock_flocks:
--   age_at_placement_days  bird age on the placement date (0 = day-old chicks)
--   target_days            farmer's planned slaughter/sale age (days)
--   target_weight_kg       farmer's planned average live weight (kg), optional
--   cycle_number           1, 2, 3 ... per coop
--   closed_date, birds_sold, total_weight_sold_kg, sale_amount
--                          filled when the cycle is ended (status 'Closed')
--
-- New table flock_weighings: sample weighings (N birds, total kg).
--
-- Targets are entered by the farmer; no breed growth standards are stored.
-- Units: canonical kg. Additive; existing rows keep working (defaults).
-- ============================================================
ALTER TABLE public.livestock_flocks
  ADD COLUMN IF NOT EXISTS age_at_placement_days integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS target_days integer,
  ADD COLUMN IF NOT EXISTS target_weight_kg numeric,
  ADD COLUMN IF NOT EXISTS cycle_number integer NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS closed_date date,
  ADD COLUMN IF NOT EXISTS birds_sold integer,
  ADD COLUMN IF NOT EXISTS total_weight_sold_kg numeric,
  ADD COLUMN IF NOT EXISTS sale_amount numeric;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'livestock_flocks_cycle_values_check') THEN
    ALTER TABLE public.livestock_flocks
      ADD CONSTRAINT livestock_flocks_cycle_values_check CHECK (
        age_at_placement_days >= 0
        AND (target_days IS NULL OR target_days > 0)
        AND (target_weight_kg IS NULL OR target_weight_kg > 0)
        AND cycle_number >= 1
        AND (birds_sold IS NULL OR birds_sold >= 0)
        AND (total_weight_sold_kg IS NULL OR total_weight_sold_kg >= 0)
        AND (sale_amount IS NULL OR sale_amount >= 0)
      );
  END IF;
END $$;

COMMENT ON COLUMN public.livestock_flocks.age_at_placement_days IS 'Bird age in days on placed_date. 0 = day-old chicks.';
COMMENT ON COLUMN public.livestock_flocks.target_days IS 'Farmer-entered planned slaughter/sale age in days.';
COMMENT ON COLUMN public.livestock_flocks.target_weight_kg IS 'Farmer-entered planned average live weight per bird (kg).';
COMMENT ON COLUMN public.livestock_flocks.cycle_number IS 'Batch number for this coop (1, 2, 3 ...).';
COMMENT ON COLUMN public.livestock_flocks.closed_date IS 'Date the cycle ended (slaughter / sale). Set together with status = Closed.';

-- ── Sample weighings ────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.flock_weighings (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  flock_id bigint NOT NULL REFERENCES public.livestock_flocks(id) ON DELETE CASCADE,
  weigh_date date NOT NULL,
  birds_weighed integer NOT NULL CHECK (birds_weighed > 0),
  total_weight_kg numeric NOT NULL CHECK (total_weight_kg > 0),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flock_weighings_pkey PRIMARY KEY (id)
);
COMMENT ON TABLE public.flock_weighings IS 'Sample weighings of a broiler batch. Average weight = total_weight_kg / birds_weighed.';

CREATE INDEX IF NOT EXISTS idx_flock_weighings_user ON public.flock_weighings USING btree (user_id);
CREATE INDEX IF NOT EXISTS idx_flock_weighings_flock_date ON public.flock_weighings USING btree (flock_id, weigh_date DESC);

ALTER TABLE public.flock_weighings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own flock weighings" ON public.flock_weighings;
CREATE POLICY "Users can view their own flock weighings"
  ON public.flock_weighings FOR SELECT TO public USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can insert their own flock weighings" ON public.flock_weighings;
CREATE POLICY "Users can insert their own flock weighings"
  ON public.flock_weighings FOR INSERT TO public
  WITH CHECK (
    auth.uid() = user_id
    AND EXISTS (SELECT 1 FROM public.livestock_flocks f WHERE f.id = flock_id AND f.user_id = auth.uid())
  );
DROP POLICY IF EXISTS "Users can delete their own flock weighings" ON public.flock_weighings;
CREATE POLICY "Users can delete their own flock weighings"
  ON public.flock_weighings FOR DELETE TO public USING (auth.uid() = user_id);

-- ── Mortality on a closed cycle is blocked ──────────────────
-- Recording or undoing deaths after the cycle ended would change the
-- bird count of a batch that no longer exists in the coop.
CREATE OR REPLACE FUNCTION public.flock_mortality_apply()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  flock_status text;
BEGIN
  IF TG_OP = 'INSERT' THEN
    SELECT status INTO flock_status FROM public.livestock_flocks WHERE id = NEW.flock_id;
    IF flock_status = 'Closed' THEN
      RAISE EXCEPTION 'This cycle is closed. Deaths can no longer be recorded.';
    END IF;
    UPDATE public.livestock_flocks
       SET bird_count = bird_count - NEW.quantity
     WHERE id = NEW.flock_id AND bird_count >= NEW.quantity;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Cannot record % deaths: the coop does not have that many birds.', NEW.quantity;
    END IF;
    RETURN NEW;
  ELSE
    SELECT status INTO flock_status FROM public.livestock_flocks WHERE id = OLD.flock_id;
    IF flock_status = 'Closed' THEN
      RAISE EXCEPTION 'This cycle is closed. Its death records can no longer be changed.';
    END IF;
    -- flock_status NULL = flock is being deleted (cascade): nothing to restore.
    UPDATE public.livestock_flocks
       SET bird_count = bird_count + OLD.quantity
     WHERE id = OLD.flock_id;
    RETURN OLD;
  END IF;
END;
$$;
