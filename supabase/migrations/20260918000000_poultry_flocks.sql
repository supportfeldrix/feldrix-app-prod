-- ============================================================
-- Poultry Flocks (bulk livestock) + daily feed & water logs
--
-- Lets a farmer register a whole coop/house as ONE record with a bird
-- count (e.g. 1000+ chickens) instead of one livestock row per bird, and
-- log the feed and water given to each coop per day.
--
-- Purely additive: does not touch public.livestock.
--
-- Units (Feldrix convention): feed_kg is canonical KILOGRAMS and water_l is
-- canonical LITRES. The UI converts to lb / gal for US farms.
--
-- RLS mirrors the existing owner-scoped pattern (user_id = auth.uid()).
-- ============================================================
CREATE TABLE IF NOT EXISTS public.livestock_flocks (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  coop_name text NOT NULL,
  species text NOT NULL DEFAULT 'Chicken',
  breed text,
  purpose text,
  bird_count integer NOT NULL CHECK (bird_count >= 0),
  placed_date date,
  purchase_price numeric,
  status text NOT NULL DEFAULT 'Active',
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT livestock_flocks_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE public.livestock_flocks IS 'A flock of birds housed in one coop/house, tracked by head count instead of per-animal rows. Tenant-isolated by user_id.';
COMMENT ON COLUMN public.livestock_flocks.purchase_price IS 'Total purchase price for the whole flock (not per bird).';

CREATE INDEX IF NOT EXISTS idx_livestock_flocks_user
  ON public.livestock_flocks USING btree (user_id);

CREATE TABLE IF NOT EXISTS public.flock_daily_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  flock_id bigint NOT NULL REFERENCES public.livestock_flocks(id) ON DELETE CASCADE,
  log_date date NOT NULL,
  feed_kg numeric CHECK (feed_kg IS NULL OR feed_kg >= 0),
  water_l numeric CHECK (water_l IS NULL OR water_l >= 0),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flock_daily_logs_pkey PRIMARY KEY (id),
  -- One log per coop per day; re-saving the same day updates it.
  CONSTRAINT flock_daily_logs_flock_date_key UNIQUE (flock_id, log_date)
);

COMMENT ON TABLE public.flock_daily_logs IS 'Feed and water supplied to a flock on a given day. Tenant-isolated by user_id.';
COMMENT ON COLUMN public.flock_daily_logs.feed_kg IS 'Feed supplied that day in CANONICAL kilograms.';
COMMENT ON COLUMN public.flock_daily_logs.water_l IS 'Water supplied that day in CANONICAL litres.';

CREATE INDEX IF NOT EXISTS idx_flock_daily_logs_user
  ON public.flock_daily_logs USING btree (user_id);
CREATE INDEX IF NOT EXISTS idx_flock_daily_logs_flock_date
  ON public.flock_daily_logs USING btree (flock_id, log_date DESC);

-- ── RLS ─────────────────────────────────────────────────────
ALTER TABLE public.livestock_flocks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.flock_daily_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own flocks" ON public.livestock_flocks;
CREATE POLICY "Users can view their own flocks"
  ON public.livestock_flocks FOR SELECT TO public USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can insert their own flocks" ON public.livestock_flocks;
CREATE POLICY "Users can insert their own flocks"
  ON public.livestock_flocks FOR INSERT TO public WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can update their own flocks" ON public.livestock_flocks;
CREATE POLICY "Users can update their own flocks"
  ON public.livestock_flocks FOR UPDATE TO public USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can delete their own flocks" ON public.livestock_flocks;
CREATE POLICY "Users can delete their own flocks"
  ON public.livestock_flocks FOR DELETE TO public USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can view their own flock logs" ON public.flock_daily_logs;
CREATE POLICY "Users can view their own flock logs"
  ON public.flock_daily_logs FOR SELECT TO public USING (auth.uid() = user_id);
-- The flock must also belong to the caller, so a log can't be attached to someone else's flock.
DROP POLICY IF EXISTS "Users can insert their own flock logs" ON public.flock_daily_logs;
CREATE POLICY "Users can insert their own flock logs"
  ON public.flock_daily_logs FOR INSERT TO public
  WITH CHECK (
    auth.uid() = user_id
    AND EXISTS (SELECT 1 FROM public.livestock_flocks f WHERE f.id = flock_id AND f.user_id = auth.uid())
  );
DROP POLICY IF EXISTS "Users can update their own flock logs" ON public.flock_daily_logs;
CREATE POLICY "Users can update their own flock logs"
  ON public.flock_daily_logs FOR UPDATE TO public USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can delete their own flock logs" ON public.flock_daily_logs;
CREATE POLICY "Users can delete their own flock logs"
  ON public.flock_daily_logs FOR DELETE TO public USING (auth.uid() = user_id);
