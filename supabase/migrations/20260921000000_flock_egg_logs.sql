-- ============================================================
-- Egg production log for layer flocks
--
-- One row per flock per day (re-saving the same day updates it):
--   eggs_collected  good eggs collected that day
--   eggs_damaged    cracked / broken / dirty eggs that day (optional)
-- Totals (today, week, month, all time) and lay % are worked out in the app.
--
-- Additive. RLS follows the other flock tables (owner only; the flock must
-- belong to the caller).
-- ============================================================
CREATE TABLE IF NOT EXISTS public.flock_egg_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  flock_id bigint NOT NULL REFERENCES public.livestock_flocks(id) ON DELETE CASCADE,
  log_date date NOT NULL,
  eggs_collected integer NOT NULL CHECK (eggs_collected >= 0),
  eggs_damaged integer NOT NULL DEFAULT 0 CHECK (eggs_damaged >= 0),
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flock_egg_logs_pkey PRIMARY KEY (id),
  CONSTRAINT flock_egg_logs_flock_date_key UNIQUE (flock_id, log_date)
);

COMMENT ON TABLE public.flock_egg_logs IS 'Daily egg collection per layer flock. One row per flock per day. Tenant-isolated by user_id.';
COMMENT ON COLUMN public.flock_egg_logs.eggs_collected IS 'Good eggs collected that day.';
COMMENT ON COLUMN public.flock_egg_logs.eggs_damaged IS 'Cracked, broken or rejected eggs that day.';

CREATE INDEX IF NOT EXISTS idx_flock_egg_logs_user ON public.flock_egg_logs USING btree (user_id);
CREATE INDEX IF NOT EXISTS idx_flock_egg_logs_flock_date ON public.flock_egg_logs USING btree (flock_id, log_date DESC);

ALTER TABLE public.flock_egg_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own egg logs" ON public.flock_egg_logs;
CREATE POLICY "Users can view their own egg logs"
  ON public.flock_egg_logs FOR SELECT TO public USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own egg logs" ON public.flock_egg_logs;
CREATE POLICY "Users can insert their own egg logs"
  ON public.flock_egg_logs FOR INSERT TO public
  WITH CHECK (
    auth.uid() = user_id
    AND EXISTS (SELECT 1 FROM public.livestock_flocks f WHERE f.id = flock_id AND f.user_id = auth.uid())
  );

DROP POLICY IF EXISTS "Users can update their own egg logs" ON public.flock_egg_logs;
CREATE POLICY "Users can update their own egg logs"
  ON public.flock_egg_logs FOR UPDATE TO public
  USING (auth.uid() = user_id)
  WITH CHECK (
    auth.uid() = user_id
    AND EXISTS (SELECT 1 FROM public.livestock_flocks f WHERE f.id = flock_id AND f.user_id = auth.uid())
  );

DROP POLICY IF EXISTS "Users can delete their own egg logs" ON public.flock_egg_logs;
CREATE POLICY "Users can delete their own egg logs"
  ON public.flock_egg_logs FOR DELETE TO public USING (auth.uid() = user_id);

-- Read-only staff access, matching the optional admin migration
-- (20260919200000). Only created if that helper exists.
DO $$
BEGIN
  IF to_regprocedure('public.can_view_farm_data()') IS NOT NULL THEN
    DROP POLICY IF EXISTS "Staff can view all flock_egg_logs" ON public.flock_egg_logs;
    CREATE POLICY "Staff can view all flock_egg_logs" ON public.flock_egg_logs
      FOR SELECT TO authenticated USING (public.can_view_farm_data());
  END IF;
END $$;
