-- ============================================================
-- Flock mortality (bird deaths) + original head count
--
-- * livestock_flocks.initial_count: head count when the flock was added
--   (bird_count stays the CURRENT count). Used for the finance record.
-- * flock_mortality: one row per death event. A trigger keeps
--   livestock_flocks.bird_count in step: inserting a row subtracts the
--   birds, deleting a row (undo a mistake) adds them back. Done in the
--   database so it is atomic and cannot drift from the history.
--
-- Additive. RLS follows the same owner-scoped pattern as the flock tables.
-- ============================================================
ALTER TABLE public.livestock_flocks
  ADD COLUMN IF NOT EXISTS initial_count integer;
UPDATE public.livestock_flocks SET initial_count = bird_count WHERE initial_count IS NULL;

CREATE TABLE IF NOT EXISTS public.flock_mortality (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  flock_id bigint NOT NULL REFERENCES public.livestock_flocks(id) ON DELETE CASCADE,
  log_date date NOT NULL,
  quantity integer NOT NULL CHECK (quantity > 0),
  cause text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT flock_mortality_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE public.flock_mortality IS 'Bird deaths in a flock. Insert/delete adjusts livestock_flocks.bird_count via trigger. Tenant-isolated by user_id.';

CREATE INDEX IF NOT EXISTS idx_flock_mortality_user ON public.flock_mortality USING btree (user_id);
CREATE INDEX IF NOT EXISTS idx_flock_mortality_flock_date ON public.flock_mortality USING btree (flock_id, log_date DESC);

-- ── Keep bird_count in sync ─────────────────────────────────
CREATE OR REPLACE FUNCTION public.flock_mortality_apply()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    UPDATE public.livestock_flocks
       SET bird_count = bird_count - NEW.quantity
     WHERE id = NEW.flock_id AND bird_count >= NEW.quantity;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'Cannot record % deaths: the coop does not have that many birds.', NEW.quantity;
    END IF;
    RETURN NEW;
  ELSE
    -- Undo: put the birds back (the flock may already be gone on cascade delete).
    UPDATE public.livestock_flocks
       SET bird_count = bird_count + OLD.quantity
     WHERE id = OLD.flock_id;
    RETURN OLD;
  END IF;
END;
$$;

DROP TRIGGER IF EXISTS trg_flock_mortality_apply ON public.flock_mortality;
CREATE TRIGGER trg_flock_mortality_apply
  BEFORE INSERT OR DELETE ON public.flock_mortality
  FOR EACH ROW EXECUTE FUNCTION public.flock_mortality_apply();

-- ── RLS (no UPDATE: correct a mistake by deleting and re-adding) ──
ALTER TABLE public.flock_mortality ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own flock mortality" ON public.flock_mortality;
CREATE POLICY "Users can view their own flock mortality"
  ON public.flock_mortality FOR SELECT TO public USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can insert their own flock mortality" ON public.flock_mortality;
CREATE POLICY "Users can insert their own flock mortality"
  ON public.flock_mortality FOR INSERT TO public
  WITH CHECK (
    auth.uid() = user_id
    AND EXISTS (SELECT 1 FROM public.livestock_flocks f WHERE f.id = flock_id AND f.user_id = auth.uid())
  );
DROP POLICY IF EXISTS "Users can delete their own flock mortality" ON public.flock_mortality;
CREATE POLICY "Users can delete their own flock mortality"
  ON public.flock_mortality FOR DELETE TO public USING (auth.uid() = user_id);
