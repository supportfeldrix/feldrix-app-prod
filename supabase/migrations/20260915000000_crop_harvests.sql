-- ============================================================
-- Crop Harvests — multi-harvest support for the Crops module
--
-- Additive, tenant-isolated child table recording individual HARVEST
-- EVENTS against a crop. This separates the crop growing CYCLE (one row
-- in public.crops) from the harvest EVENTS that occur during it, so a
-- cut-and-come-again crop (e.g. Spinach) can be harvested repeatedly while
-- the crop stays active, and a single-harvest crop (e.g. Maize) records one
-- harvest and is then finished.
--
-- IMPORTANT — this migration is purely additive:
--   * It does NOT modify or delete any existing crops rows.
--   * It does NOT change the crops table schema.
--   * The terminal state remains crops.status = 'Harvested' (unchanged).
--     "Record Harvest" = insert a crop_harvests row.
--     "Finish Crop"    = (optionally record a final harvest) + set
--                        crops.status = 'Harvested'.
--
-- Units convention (documented Feldrix standard):
--   quantity is stored CANONICALLY in KILOGRAMS (kg), matching the app's
--   central mass convention (see src/utils/units.js formatMass). The UI
--   converts to the farm's display unit (kg / lb) at the display boundary
--   only. quantity_unit records the canonical storage unit ('kg') so the
--   value is self-describing and future-proof.
--
-- Ownership follows the existing crops / ground_samples RLS pattern exactly:
-- owner-scoped by user_id = auth.uid().
-- ============================================================

CREATE TABLE IF NOT EXISTS public.crop_harvests (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  crop_id bigint NOT NULL REFERENCES public.crops(id) ON DELETE CASCADE,
  harvest_date date NOT NULL,
  quantity numeric,
  quantity_unit text DEFAULT 'kg'::text,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT crop_harvests_pkey PRIMARY KEY (id)
);

COMMENT ON TABLE public.crop_harvests IS 'Individual harvest events for a crop (multi-harvest support). Tenant-isolated by user_id. A crop staying active is harvested repeatedly; harvest history is preserved when the crop is finished.';
COMMENT ON COLUMN public.crop_harvests.quantity IS 'Harvested quantity in CANONICAL kilograms (kg). Nullable — a harvest can be recorded without a measured quantity. UI converts to the farm display unit.';
COMMENT ON COLUMN public.crop_harvests.quantity_unit IS 'Canonical storage unit for quantity. Always ''kg''; display conversion happens in the UI via units.js.';

-- Indexes: owner lookups, per-crop history (newest first), and date ranges.
CREATE INDEX IF NOT EXISTS idx_crop_harvests_user
  ON public.crop_harvests USING btree (user_id);
CREATE INDEX IF NOT EXISTS idx_crop_harvests_crop
  ON public.crop_harvests USING btree (crop_id, harvest_date DESC);
CREATE INDEX IF NOT EXISTS idx_crop_harvests_harvest_date
  ON public.crop_harvests USING btree (harvest_date DESC);

-- ── RLS (mirrors crops / ground_samples policies exactly) ───
ALTER TABLE public.crop_harvests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Users can view their own crop harvests" ON public.crop_harvests;
CREATE POLICY "Users can view their own crop harvests"
  ON public.crop_harvests FOR SELECT TO public
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own crop harvests" ON public.crop_harvests;
CREATE POLICY "Users can insert their own crop harvests"
  ON public.crop_harvests FOR INSERT TO public
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update their own crop harvests" ON public.crop_harvests;
CREATE POLICY "Users can update their own crop harvests"
  ON public.crop_harvests FOR UPDATE TO public
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can delete their own crop harvests" ON public.crop_harvests;
CREATE POLICY "Users can delete their own crop harvests"
  ON public.crop_harvests FOR DELETE TO public
  USING (auth.uid() = user_id);
